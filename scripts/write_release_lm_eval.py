#!/usr/bin/env python3
"""Write docs/RELEASE_LM_EVAL.md from results/release_eval/*.json (validation-only numbers).

    python scripts/write_release_lm_eval.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
E = os.path.join(ROOT, "results", "release_eval")
NAME = dict(iam="IAM", rimes="RIMES", bentham="Bentham", saintgall="Saint Gall", washington="Washington")
CORPORA = list(NAME)
SPECS = ["o6m1", "o8m2", "o8m1", "o9m1", "o10m2", "o10m1"]
RELEASED = "o8m1"


def f(x):
    return "—" if x is None else f"{100 * x:.2f}"


def main():
    lm = json.load(open(os.path.join(E, "lm_validation.json")))
    t5 = json.load(open(os.path.join(E, "t5_validation.json")))
    grid = json.load(open(os.path.join(E, "lm_size_grid.json")))["rows"]
    lat = json.load(open(os.path.join(E, "latency.json")))
    size = {(r["lang"], r["order"], r["min_count"]): r for r in grid}
    out = ["# Released character LM: validation evaluation", "",
           "Generated by `scripts/write_release_lm_eval.py` from `results/release_eval/*.json`. **Validation splits only**;",
           "no test line was decoded for this document. CER in %.", "",
           "## Why a separate LM", "",
           "The decoding experiments (`ensemble_rescore.py`, `docs/FINAL_REPORT_T5.md`) fit the character n-gram at",
           "decode time on the corpus's TRAINING transcriptions plus Wikipedia-derived lines. An order-9/10 n-gram fitted",
           "on a few thousand benchmark lines effectively redistributes those transcriptions (IAM, RIMES: CC BY-NC 4.0;",
           "Washington, Saint Gall: IAM-HistDB non-commercial terms), and CC BY-SA Wikipedia text cannot be mixed with",
           "NC text in one released file (`docs/audit_2026_10/LICENSING.md` §2). The **released LM is fitted on the",
           "Wikipedia-derived text only** (`synth/text_{en,fr,la}.txt`: 400,000 / 200,000 / 100,000 line fragments),",
           "licensed CC BY-SA 4.0, and stored in its own repository. `scripts/build_corpus_lm.py` rebuilds the",
           "experiments' corpus + Wikipedia LM for users who hold the archives (local use only).", "",
           "## Decoder (identical in all columns)", "",
           "`htrjand.lmdecode.nbest_rescore` = the single-member case of `ensemble_rescore.py`: CTC prefix beam search",
           "(beam 16, prune -9) with the LM at gen_alpha 0.2 / gen_beta 0.5 gives the 8-best list; each candidate is",
           "rescored by its exact CTC log-likelihood + alpha x LM + beta x length; alpha in {0, .1, .2, .3, .4, .6, .8, 1}",
           "x beta in {0, .5, 1, 1.5, 2, 3, 4, 5} chosen on the full validation split (lowest CER, WER breaks ties), as",
           "the experiments did. LM = `CompactCharLM` (stupid backoff 0.4; with min_count 1 its scores equal",
           "`decode.CharLM` for every query the decoder makes, `tests/test_release.py`).", "",
           "## 1. Size of the Wikipedia LM (entries = stored n-grams + contexts)", "",
           "| language | order | min_count | entries | gzip MB |", "|---|---:|---:|---:|---:|"]
    for (lang, o, m), r in sorted(size.items()):
        if m in (1, 2, 3) and o in (6, 8, 9, 10):
            out.append(f"| {lang} | {o} | {m} | {r['entries']:,} | {r['bytes'] / 1e6:.1f} |")
    out += ["", "min_count > 1 prunes n-grams of order >= 3 seen fewer times; context totals keep their unpruned value.", "",
            "## 2. Seed-1 per-corpus Students: greedy vs Wikipedia LM vs the experiments' corpus + Wikipedia LM", "",
            "| corpus | greedy | " + " | ".join(f"wiki {s}" for s in SPECS) + " | corpus + wiki (reproduced) | corpus + wiki (reported) |",
            "|---|---:|" + "---:|" * len(SPECS) + "---:|---:|"]
    keys = {r["corpus"]: k for k, r in lm.items() if k.split("|")[0].endswith("-student/" + r["corpus"])}
    mean = {s: [] for s in SPECS}
    for c in CORPORA:
        r = lm[keys[c]]
        w = r.get("wiki_lm", {})
        cp = r.get("corpus_plus_wiki_lm", {})
        for s in SPECS:
            if s in w:
                mean[s].append(w[s]["cer"])
        out.append(f"| {NAME[c]} | {f(r['greedy']['cer'])} | " + " | ".join(f(w.get(s, {}).get("cer")) for s in SPECS)
                   + f" | {f(cp.get('cer'))} | {f(cp.get('reported_valid_cer'))} |")
    out.append("| mean | | " + " | ".join(f(sum(mean[s]) / len(mean[s])) if mean[s] else "—" for s in SPECS) + " | | |")
    out += ["", "Models: `ft_iam_c128_student_kd_s1`, `ft_rimes_c128_student_kd_s1`, `ft_bentham_c128_student_kd_s1`,",
            "`nopt_sg_student_s1`, `ft_washington_c128_student_s1`. Spec `oKmN` = order K, min_count N. The",
            "\"reproduced\" column re-runs the experiments' LM (training transcriptions + the same Wikipedia lines, same",
            "order) through the release decoder at the alpha / beta `ensemble_rescore.py` chose; it equals the reported",
            "validation CER of `results/ens_<corpus>_<run>_wiki.json` on every corpus: "
            + ", ".join(f"{NAME[c]} {'yes' if lm[keys[c]].get('corpus_plus_wiki_lm', {}).get('reproduces_reported') else 'NO'}" for c in CORPORA) + ".", "",
            "Alpha / beta selected per spec (wiki):", ""]
    for c in CORPORA:
        w = lm[keys[c]].get("wiki_lm", {})
        out.append(f"- {NAME[c]}: " + "; ".join(f"{s} {w[s]['alpha']}/{w[s]['beta']}" for s in SPECS if s in w))
    ctl_p = os.path.join(ROOT, "results", "control_lm_source.json")
    if os.path.exists(ctl_p):
        ctl = {x["corpus"]: x for x in json.load(open(ctl_p))["rows"] if x["seed"] == 1}
        out += ["", "Cross-check with the independent control `results/control_lm_source.json` (Wikipedia-only arm of",
                "`ensemble_rescore.py --lm-no-train-text`, unpruned, order 10 for IAM and 9 otherwise, 400,000 English lines",
                "for IAM but 200,000 for Bentham / Washington; validation CER):", "",
                "| corpus | control Wikipedia-only (its order / lines) | this table, same order on all lines (o10m1 IAM; o9m1 others) | control train-only LM |",
                "|---|---:|---:|---:|"]
        for c in CORPORA:
            x = ctl.get(c)
            if not x:
                continue
            w = lm[keys[c]].get("wiki_lm", {})
            same = w.get("o10m1" if c == "iam" else "o9m1", {}).get("cer")
            out.append(f"| {NAME[c]} | {f(x['wiki_only']['valid']['cer'])} | {f(same)} | {f(x['train_only']['valid']['cer'])} |")
        out += ["", "The two agree where the LM text is the same (IAM, RIMES, Saint Gall). The control also shows that an LM",
                "fitted on the training transcriptions ALONE gives most of the gain of the combined LM (CONTROLS.md C1),",
                "which is why the released Wikipedia-only LM stays behind the paper's corpus + Wikipedia LM."]
    en = size[("en", 8, 1)]
    fr, la = size[("fr", 8, 1)], size[("la", 8, 1)]
    loads = lat.get("load_seconds", {})
    mn = {s: 100 * sum(v) / len(v) for s, v in mean.items() if v}
    best = min(mn, key=mn.get)
    bo, bm = int(best[1:].split("m")[0]), int(best.split("m")[1])
    frac = 100 * en["entries"] / size[("en", bo, bm)]["entries"]
    out += ["", f"## 3. Choice: order 8, no pruning (`{RELEASED}`)", "",
            f"On the five-corpus mean, `{RELEASED}` ({mn[RELEASED]:.2f}) is {mn[RELEASED] - mn[best]:+.2f} pp from the best spec "
            f"`{best}` ({mn[best]:.2f}) with {frac:.0f} % of its English entries; pruning at min_count 2 (`o8m2`, "
            f"{mn['o8m2']:.2f}) costs {mn['o8m2'] - mn[RELEASED]:+.2f} pp.",
            f"Files: en {en['bytes'] / 1e6:.1f} MB ({en['entries']:,} entries),",
            f"fr {fr['bytes'] / 1e6:.1f} MB, la {la['bytes'] / 1e6:.1f} MB, i.e. at most 40 MB per language (limit 150 MB).",
            f"Load time on CPU: en {loads.get('lm_file_en', '—')} s, fr {loads.get('lm_file_fr', '—')} s, la {loads.get('lm_file_la', '—')} s;",
            "resident memory of the loaded English model about 1.2 GB (measured peak RSS increase 1.16 GB).",
            "Cost against the experiments' corpus + Wikipedia LM on validation: see section 2 (the released LM knows no",
            "corpus-specific vocabulary, names or spelling conventions).", "",
            "## 4. Released LM on every released model (validation, alpha / beta stored in config.json)", "",
            "| model | corpus | greedy | released LM | alpha / beta |", "|---|---|---:|---:|---|"]
    for k, r in sorted(lm.items()):
        w = r.get("wiki_lm", {}).get("charlm")
        if w:
            out.append(f"| {k.split('|')[0]} | {NAME[r['corpus']]} | {f(r['greedy']['cer'])} | {f(w['cer'])} | {w['alpha']} / {w['beta']} |")
    out += ["", "## 5. T5 gate lexicon (seed-1 per-corpus Students, raw-CTC base, validation)", "",
            "The T5 out-of-lexicon detector used the corpus TRAINING lexicon in the experiments (not redistributed). The",
            "release ships Wikipedia word lists. Same T5 candidates (the released corrector t5_ext_ctx1 throughout; for",
            "Washington and Saint Gall raw CTC the validation-selected corrector of the results is t5_ctx0 / t5_ctx1, which",
            "is not released), gate grid re-selected per lexicon:", "",
            "| corpus | raw CTC | T5, training lexicon (experiments) | T5, Wikipedia words >= 2 (released) | T5, all Wikipedia words |",
            "|---|---:|---:|---:|---:|"]
    for c in CORPORA:
        k = keys[c]
        r = t5.get(k, {}).get("ctc", {})
        if r:
            out.append(f"| {NAME[c]} | {f(r['base']['cer'])} | {f(r.get('with_training_lexicon', {}).get('cer'))} | "
                       f"{f(r['selected']['cer'])} | {f(r.get('with_wiki_all_words_lexicon', {}).get('cer'))} |")
    rep = []
    for c in CORPORA:
        fn = "t5_saintgall_nopt_student_ctc_t5_ext_ctx1.json" if c == "saintgall" else f"t5_{c}_ftstudent_ctc_t5_ext_ctx1.json"
        r0 = json.load(open(os.path.join(ROOT, "results", fn)))
        tr = t5.get(keys[c], {}).get("ctc", {}).get("with_training_lexicon", {}).get("cer")
        rep.append(f"{NAME[c]} {f(r0['selected']['cer'])} ({'same' if tr is not None and abs(tr - r0['selected']['cer']) < 1e-12 else 'DIFFERENT'})")
    out += ["", "Reported validation CER of the experiments' gate (`results/t5_<corpus>_..._ctc_t5_ext_ctx1.json`, training",
            "lexicon) and whether the training-lexicon column reproduces it: " + ", ".join(rep) + ".", "",
            "## 6. Released T5 gates (validation)", "",
            "| model | corpus | base | before | after | detect / apply / theta | lines changed |", "|---|---|---|---:|---:|---|---:|"]
    for k, r in sorted(t5.items()):
        for b in ("ctc", "lm"):
            s = r[b]["selected"]
            out.append(f"| {k.split('|')[0]} | {NAME[r['corpus']]} | {'raw CTC' if b == 'ctc' else 'released LM'} | "
                       f"{f(r[b]['base']['cer'])} | {f(s['cer'])} | {s['detect']} / {s['apply']} / {s['theta']} | {s['n_changed']} |")
    out += ["", "theta = 1.01 means the gate never applies a correction on that path.", ""]
    open(os.path.join(ROOT, "docs", "RELEASE_LM_EVAL.md"), "w", encoding="utf-8").write("\n".join(out))
    print("wrote docs/RELEASE_LM_EVAL.md")


if __name__ == "__main__":
    main()
