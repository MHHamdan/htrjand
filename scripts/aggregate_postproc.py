#!/usr/bin/env python3
"""Raw versus post-processed test results (T5 and lexicon-based correction stages), seed means.

    python scripts/aggregate_postproc.py [--results results] [--out <file.md>]

Reads results/postproc_<tag>.json written by htrjand.postprocess apply.
"""
import argparse
import glob
import json
import os
import re
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONDS = ["raw", "t5_word_selective", "t5_selective", "t5_all", "lexicon", "t5_selective_lexicon"]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "results"))
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    fam = defaultdict(list)
    for f in sorted(glob.glob(os.path.join(a.results, "postproc_*.json"))):
        r = json.load(open(f))
        tag = os.path.basename(f)[len("postproc_"):-len(".json")]
        fam[re.sub(r"_s\d+$", "", tag)].append(r)
    lines = ["| family | seeds | condition | test CER % | test WER % | test SER % | θ / δ | lines corrected |",
             "|---|---|---|---:|---:|---:|---|---:|"]

    def ms(xs, nd=2):
        xs = [100 * x for x in xs]
        return f"{np.mean(xs):.{nd}f}" if len(xs) == 1 else f"{np.mean(xs):.{nd}f} ± {np.std(xs, ddof=1):.{nd}f}"
    for key, rs in sorted(fam.items()):
        for c in CONDS:
            if c not in rs[0]["test"]:
                continue
            lines.append("| " + " | ".join([
                key, str(len(rs)), c,
                ms([r["test"][c]["cer"] for r in rs]), ms([r["test"][c]["wer"] for r in rs]),
                ms([r["test"][c]["ser"] for r in rs]),
                "/".join(sorted({f"{r['theta']}/{r['delta']}" for r in rs})),
                f"{np.mean([r['n_corrected'] for r in rs]):.0f} of {rs[0]['n_test']}"]) + " |")
    text = "\n".join(lines)
    print(text)
    if a.out:
        hdr = ("# Post-processing results (T5 corrector, lexicon-based correction)\n\n"
               "Generated by `scripts/aggregate_postproc.py` from `results/postproc_*.json`. The corrector is "
               "T5-small fine-tuned on cross-decoded TRAINING pairs; the lexicon is the training word list; "
               "θ and δ are chosen on validation; the test split is corrected once. `raw` is the recogniser "
               "alone; `t5_word_selective` is the condition selected on validation (T5 post-processing with the "
               "dictionary and a bounded candidate distance); the other conditions are reported for "
               "transparency and were not selected.\n\n")
        open(a.out, "w").write(hdr + text + "\n")


if __name__ == "__main__":
    main()
