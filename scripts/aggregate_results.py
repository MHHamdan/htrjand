#!/usr/bin/env python3
"""Seed means ± sd of the base-configuration and screening results, as a Markdown table.

    python scripts/aggregate_results.py [--results results] [--out docs/RESULTS_RECONSTRUCTION.md]

Groups results/<tag>_test.json by tag with the trailing _s<seed> removed.
Every number is read from a result file written by htrjand.evaluate;
nothing is typed by hand.
"""
import argparse
import glob
import json
import os
import re
from collections import defaultdict

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default=os.path.join(ROOT, "results"))
    ap.add_argument("--runs", default=os.path.join(ROOT, "runs"))
    ap.add_argument("--split", default="test")
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    fam = defaultdict(list)
    for f in sorted(glob.glob(os.path.join(a.results, f"*_{a.split}.json"))):
        r = json.load(open(f))
        key = re.sub(r"_s\d+(_kd)?$", lambda m: m.group(1) or "", r["tag"])
        log = os.path.join(a.runs, r["tag"], "train_log.json")
        hours = None
        if os.path.exists(log):
            j = json.load(open(log))
            hours = j.get("elapsed_s", 0) / 3600
            r["epochs_run"] = j.get("epochs_run")
        r["hours"] = hours
        fam[key].append(r)
    lines = ["| family | corpus | preset | seeds | test CER % | test WER % | test SER % | best val CER % | params (deployed) | ms/line | h/run | epochs |",
             "|---|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    def ms(xs, scale=100.0, nd=2):
        xs = [x for x in xs if x is not None]
        if not xs:
            return "–"
        m = np.mean(xs) * scale
        return f"{m:.{nd}f}" if len(xs) == 1 else f"{m:.{nd}f} ± {np.std(xs, ddof=1) * scale:.{nd}f}"
    for key, rs in sorted(fam.items()):
        r0 = rs[0]
        lines.append("| " + " | ".join([
            key, r0["dataset"], r0["preset"], ",".join(str(r.get("seed")) for r in rs),
            ms([r["cer"] for r in rs]), ms([r["wer"] for r in rs]), ms([r["ser"] for r in rs]),
            ms([r.get("best_val_cer") for r in rs]),
            f"{r0['params_total']:,} ({r0['params_deployed']:,})",
            ms([r.get("latency_bs1_ms") for r in rs], 1.0, 2),
            ms([r.get("hours") for r in rs], 1.0, 2),
            ms([r.get("epochs_run") for r in rs], 1.0, 0)]) + " |")
    text = "\n".join(lines)
    print(text)
    if a.out:
        hdr = ("# Base-configuration and screening results (68 x 864)\n\n"
               "Generated by `scripts/aggregate_results.py` from `results/*_test.json`. "
               "Official partitions, greedy CTC decoding, no lexicon, no language model, no post-processing. "
               "The test split was decoded once per checkpoint; checkpoints were chosen on validation CER.\n\n")
        open(a.out, "w").write(hdr + text + "\n")


if __name__ == "__main__":
    main()
